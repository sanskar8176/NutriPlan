import type { Food } from "@prisma/client";
import { prisma } from "@/lib/prisma";
import type { MealTime, DietTag, FoodItem } from "@/lib/food-data";
import { allergenKeywordsFor, excludeAllergens } from "@/lib/allergens";
import { safeImageUrl } from "@/lib/images";

/** Maps a Food row to the client-facing FoodItem shape (image host-checked, numbers rounded). */
export function dbFoodToItem(f: Food, mealTime?: MealTime, aiGenerated?: boolean): FoodItem {
  return {
    id:          f.id,
    name:        f.name,
    description: f.description ?? "",
    calories:    Math.round(f.calories),
    proteinG:    Math.round(f.proteinG),
    carbsG:      Math.round(f.carbsG),
    fatG:        Math.round(f.fatG),
    mealTime:    mealTime ? [mealTime] : (f.mealTimes as MealTime[]),
    dietTags:    f.dietTags as DietTag[],
    image:       safeImageUrl(f.image, f.category),
    servingSize: f.servingSize,
    // Negative fdcIds are synthetic (AI or materialised static items); only AI ones get the badge.
    aiGenerated: aiGenerated ?? (f.fdcId < 0 && f.category !== "static"),
  };
}

/** Minimum catalogue size before the database is preferred over the bundled static list. */
export const MIN_DB_FOODS = 10;

/**
 * Builds a plan from foods already stored in the database (USDA seed + foods
 * previously generated by the AI). No external calls.
 * Returns null when the table is too small to build a sensible plan, so the
 * caller can fall through to the static catalogue (and label it honestly).
 */
export async function getMealPlanFromDB(
  dietType: DietTag,
  targetCalories: number,
  allergies: string[] = [],
  seed = 0,
): Promise<Record<MealTime, FoodItem[]> | null> {
  const count = await prisma.food.count({ where: { isActive: true } });
  if (count < MIN_DB_FOODS) return null;

  // Exclude anything whose name mentions an allergen keyword ("Nuts" → almond, cashew, ...).
  const keywords = allergenKeywordsFor(allergies);
  const allergyWhere = keywords.length > 0
    ? { NOT: { OR: keywords.map((k) => ({ name: { contains: k, mode: "insensitive" as const } })) } }
    : {};

  const fetchPool = async (mealTime: MealTime): Promise<Food[]> => {
    const rows = await prisma.food.findMany({
      where: { isActive: true, mealTimes: { has: mealTime }, dietTags: { has: dietType }, ...allergyWhere },
      orderBy: { fdcId: "asc" },
      take: 50,
    });
    if (rows.length > 0) return rows;
    // Fallback: ignore the diet filter but never the allergy filter.
    return prisma.food.findMany({
      where: { isActive: true, mealTimes: { has: mealTime }, ...allergyWhere },
      orderBy: { fdcId: "asc" },
      take: 50,
    });
  };

  const [bfPool, lunchPool, dinnerPool, snackPool] = await Promise.all([
    fetchPool("breakfast"), fetchPool("lunch"), fetchPool("dinner"), fetchPool("snack"),
  ]);

  // Rotate each pool by seed so "Regenerate" gives different foods.
  const rotate = <T>(arr: T[], offset: number) => {
    if (arr.length === 0) return arr;
    const o = ((offset % arr.length) + arr.length) % arr.length;
    return [...arr.slice(o), ...arr.slice(0, o)];
  };

  const usedIds = new Set<string>();
  const pickUnique = (pool: Food[], limit: number): FoodItem[] => {
    const picked: FoodItem[] = [];
    // Second-pass allergen check also covers the description column.
    for (const row of excludeAllergens(pool, allergies)) {
      if (picked.length >= limit) break;
      if (usedIds.has(row.id)) continue;
      usedIds.add(row.id);
      picked.push(dbFoodToItem(row));
    }
    return picked;
  };

  return {
    breakfast: pickUnique(rotate(bfPool, seed), 1),
    lunch:     pickUnique(rotate(lunchPool, seed + 7), 1),
    dinner:    pickUnique(rotate(dinnerPool, seed + 13), 1),
    snack:     pickUnique(rotate(snackPool, seed + 3), 2),
  };
}

"use client";
import { useSearchParams, useRouter } from "next/navigation";
import { useState, useEffect, useMemo } from "react";
import Image from "next/image";
import { motion, AnimatePresence } from "framer-motion";
import { useSession } from "next-auth/react";
import {
  ArrowLeft, RefreshCw, Flame, Beef, Wheat, Droplets,
  BookmarkCheck, Bookmark, Loader2, Sparkles, Database, Image as ImageIcon, CheckCircle2,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/index";
import { MacroDonutChart } from "@/components/charts/macro-donut";
import { computeNutritionPlan, getBMICategory, calculateBMI } from "@/lib/calculations";
import type { MealTime, FoodItem } from "@/lib/food-data";
import { resultsParamsSchema, searchParamsToObject } from "@/lib/api-schemas";
import type { ResultsParams } from "@/lib/api-schemas";
import type { MealPlanResponse, MealPlanSource, MealsByTime } from "@/lib/types";

const MEAL_LABELS: Record<MealTime, string> = {
  breakfast: "🌅 Breakfast",
  lunch: "☀️ Lunch",
  dinner: "🌙 Dinner",
  snack: "🍎 Snacks",
};

const MEAL_ORDER: MealTime[] = ["breakfast", "lunch", "dinner", "snack"];

const MACRO_CARDS = [
  { key: "calories" as const, label: "Daily Calories", unit: "kcal", icon: Flame, color: "text-orange-500" },
  { key: "proteinG" as const, label: "Protein", unit: "g", icon: Beef, color: "text-green-600" },
  { key: "carbsG" as const, label: "Carbs", unit: "g", icon: Wheat, color: "text-amber-500" },
  { key: "fatG" as const, label: "Fat", unit: "g", icon: Droplets, color: "text-orange-400" },
];

const AI_STAGES = [
  { icon: Sparkles,     label: "Asking the AI nutritionist…",     detail: "Composing a personalised Indian-first meal plan" },
  { icon: Database,     label: "Cross-checking nutrition data…",  detail: "Verifying calories & macros against the USDA database" },
  { icon: ImageIcon,    label: "Fetching food photos…",           detail: "Finding an image for each meal" },
  { icon: CheckCircle2, label: "Finalising your plan…",           detail: "Almost ready!" },
];

const SOURCE_LABELS: Record<MealPlanSource, string> = {
  gemini:   "Generated by Gemini and cross-checked with USDA data",
  local:    "Generated by your local model and cross-checked with USDA data",
  database: "Built from our verified food database",
  static:   "Built from the bundled starter catalogue (AI and database unavailable right now)",
};

const CACHE_VERSION = "v2";

export function hasMealPlanContent(meals: MealsByTime | null | undefined): boolean {
  return !!meals && MEAL_ORDER.some((t) => (meals[t]?.length ?? 0) > 0);
}

/** Reads and validates the URL parameters; returns null when they are missing or out of range. */
export function parseResultsParams(sp: URLSearchParams): ResultsParams | null {
  const parsed = resultsParamsSchema.safeParse(searchParamsToObject(sp));
  return parsed.success ? parsed.data : null;
}

function MealLoadingSkeleton({ fromSaved }: { fromSaved: boolean }) {
  const [stage, setStage] = useState(0);
  const [dots, setDots]   = useState("");

  useEffect(() => {
    if (fromSaved) return; // saved plans load fast — just show pulse
    const stageTimer = setInterval(() => setStage((s) => Math.min(s + 1, AI_STAGES.length - 1)), 6000);
    const dotsTimer  = setInterval(() => setDots((d) => d.length >= 3 ? "" : d + "."), 500);
    return () => { clearInterval(stageTimer); clearInterval(dotsTimer); };
  }, [fromSaved]);

  if (fromSaved) {
    return (
      <div className="grid sm:grid-cols-2 gap-5" aria-busy="true" aria-label="Loading saved plan">
        {MEAL_ORDER.map((t) => (
          <div key={t} className="rounded-xl border border-[var(--border)] bg-[var(--card)] h-32 animate-pulse" />
        ))}
      </div>
    );
  }

  const current = AI_STAGES[stage];
  const Icon    = current.icon;

  return (
    <div className="flex flex-col items-center gap-6 py-10" aria-busy="true" aria-live="polite">
      <div className="relative">
        <div className="w-16 h-16 rounded-full bg-[var(--primary)]/10 flex items-center justify-center">
          <Icon className="w-7 h-7 text-[var(--primary)] animate-pulse" />
        </div>
        <div className="absolute inset-0 rounded-full border-2 border-[var(--primary)]/30 animate-ping" />
      </div>

      <div className="text-center">
        <p className="font-heading font-semibold text-lg">{current.label}{dots}</p>
        <p className="text-sm text-[var(--muted-foreground)] mt-1">{current.detail}</p>
      </div>

      <div className="flex gap-2">
        {AI_STAGES.map((s, i) => (
          <motion.div
            key={s.label}
            className="h-2 rounded-full bg-[var(--primary)]"
            animate={{ width: i === stage ? 24 : 8, opacity: i <= stage ? 1 : 0.3 }}
            transition={{ duration: 0.3 }}
          />
        ))}
      </div>

      <div className="w-full grid sm:grid-cols-2 gap-5 mt-2">
        {MEAL_ORDER.map((t, i) => (
          <motion.div
            key={t}
            className="rounded-xl border border-[var(--border)] bg-[var(--card)] h-28 overflow-hidden"
            animate={{ opacity: [0.4, 0.7, 0.4] }}
            transition={{ duration: 1.5, repeat: Infinity, delay: i * 0.2 }}
          >
            <div className="flex h-full">
              <div className="w-24 bg-[var(--muted)]/40 flex-shrink-0" />
              <div className="flex-1 p-3 flex flex-col gap-2 justify-center">
                <div className="h-3 bg-[var(--muted)]/40 rounded w-3/4" />
                <div className="h-2 bg-[var(--muted)]/30 rounded w-1/2" />
                <div className="h-2 bg-[var(--muted)]/20 rounded w-2/3" />
              </div>
            </div>
          </motion.div>
        ))}
      </div>
    </div>
  );
}

function InvalidParams() {
  const router = useRouter();
  return (
    <div className="min-h-screen flex items-center justify-center px-4">
      <div className="text-center max-w-md">
        <div className="text-5xl mb-4">🧮</div>
        <h1 className="font-heading text-2xl font-bold mb-2">We need a few details first</h1>
        <p className="text-[var(--muted-foreground)] mb-6">
          This page needs a valid profile (age, height, weight, activity, goal and diet). Fill in the short form and we&apos;ll build your plan.
        </p>
        <Button onClick={() => router.push("/plan")}>Build My Plan</Button>
      </div>
    </div>
  );
}

export function ResultsDashboard() {
  const searchParams = useSearchParams();
  const params = useMemo(() => parseResultsParams(new URLSearchParams(searchParams.toString())), [searchParams]);
  if (!params) return <InvalidParams />;
  return <ResultsView params={params} />;
}

function ResultsView({ params }: { params: ResultsParams }) {
  const router = useRouter();
  const { data: session, status } = useSession();

  const planId    = params.planId ?? null;
  const fromSaved = params.fromSaved === "1";

  const [seed, setSeed] = useState(0);
  const [saving, setSaving] = useState(false);
  const [saved, setSaved] = useState(fromSaved);
  const [saveError, setSaveError] = useState("");
  const [meals, setMeals] = useState<MealsByTime | null>(null);
  const [source, setSource] = useState<MealPlanSource | null>(null);
  const [loadError, setLoadError] = useState("");
  const [mealsLoading, setMealsLoading] = useState(true);

  const stats = {
    age: params.age, gender: params.gender, heightCm: params.heightCm, weightKg: params.weightKg,
    activityLevel: params.activityLevel, goal: params.goal, targetRateKg: params.targetRateKg ?? 0.5,
  };
  const dietType  = params.dietType;
  const allergies = params.allergies;
  const bmi       = params.bmi ?? calculateBMI(stats.weightKg, stats.heightCm);
  const plan      = computeNutritionPlan(stats);
  const goalLabel = { lose: "Weight Loss", maintain: "Maintenance", gain: "Muscle Gain" }[stats.goal];

  const generationQuery = useMemo(() => new URLSearchParams({
    dietType,
    age:           String(stats.age),
    gender:        stats.gender,
    weightKg:      String(stats.weightKg),
    heightCm:      String(stats.heightCm),
    goal:          stats.goal,
    activityLevel: stats.activityLevel,
    targetRateKg:  String(stats.targetRateKg),
    seed:          String(seed),
    allergies:     allergies.join(","),
  }).toString(), [dietType, stats.age, stats.gender, stats.weightKg, stats.heightCm, stats.goal, stats.activityLevel, stats.targetRateKg, seed, allergies]);

  const cacheKey = planId ? `saved-plan:${CACHE_VERSION}:${planId}` : `generated-plan:${CACHE_VERSION}:${generationQuery}`;
  const canSave  = !mealsLoading && hasMealPlanContent(meals);

  // Fetch meal plan — from saved planId (no AI) or fresh generation
  useEffect(() => {
    let active = true;
    const loadMeals = async () => {
      setLoadError("");
      if (!planId) {
        const cached = sessionStorage.getItem(cacheKey);
        if (cached) {
          try {
            const parsed = JSON.parse(cached) as MealPlanResponse;
            if (active && hasMealPlanContent(parsed.meals)) {
              setMeals(parsed.meals);
              setSource(parsed.source);
              setMealsLoading(false);
              return;
            }
          } catch {
            sessionStorage.removeItem(cacheKey);
          }
        }
      }

      setMealsLoading(true);
      const url = planId
        ? `/api/meal-plan?planId=${encodeURIComponent(planId)}`
        : `/api/meal-plan?${generationQuery}`;

      try {
        const response = await fetch(url);
        if (!active) return;
        if (!response.ok) {
          const data = await response.json().catch(() => ({}));
          setMeals(null);
          setLoadError(
            response.status === 401 ? "Please sign in to view this saved plan."
            : response.status === 404 ? "This saved plan could not be found."
            : response.status === 429 ? "You're generating plans very quickly — please wait a minute and try again."
            : (data.error ?? "Could not load the meal plan."),
          );
          return;
        }
        const data = await response.json() as MealPlanResponse;
        setMeals(data.meals);
        setSource(data.source);
        if (!planId && hasMealPlanContent(data.meals)) {
          sessionStorage.setItem(cacheKey, JSON.stringify(data));
        }
      } catch {
        if (!active) return;
        setMeals(null);
        setLoadError("Network error while loading the meal plan.");
      } finally {
        if (active) setMealsLoading(false);
      }
    };

    void loadMeals();
    return () => { active = false; };
  }, [planId, generationQuery, cacheKey]);

  const handleSave = async () => {
    if (!session) {
      router.push(`/auth/signin?callbackUrl=${encodeURIComponent(window.location.pathname + window.location.search)}`);
      return;
    }
    if (mealsLoading || !hasMealPlanContent(meals)) {
      setSaveError("Please wait until your meal plan is fully generated before saving.");
      return;
    }

    setSaving(true);
    setSaveError("");
    try {
      const mealItems: Array<{ foodId: string; mealTime: MealTime; position: number; aiGenerated: boolean }> = [];
      for (const mt of MEAL_ORDER) {
        (meals?.[mt] ?? []).forEach((item, idx) => {
          mealItems.push({ foodId: item.id, mealTime: mt, position: idx, aiGenerated: item.aiGenerated ?? false });
        });
      }

      const res = await fetch("/api/plans", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          name: `${goalLabel} Plan`,
          age: stats.age,
          gender: stats.gender,
          heightCm: stats.heightCm,
          weightKg: stats.weightKg,
          activityLevel: stats.activityLevel,
          goal: stats.goal,
          targetRateKg: stats.targetRateKg,
          dietType,
          allergies,
          meals: mealItems,
        }),
      });
      if (!res.ok) {
        const data = await res.json().catch(() => ({}));
        setSaveError(data.error ?? (res.status === 401 ? "Your session expired — please sign in again." : "Failed to save plan"));
      } else {
        setSaved(true);
      }
    } catch {
      setSaveError("Network error — please try again");
    } finally {
      setSaving(false);
    }
  };

  const bmiInfo = bmi > 0 ? getBMICategory(bmi) : null;
  const bmiPct  = Math.min(100, Math.max(0, ((bmi - 15) / 25) * 100));

  return (
    <div className="min-h-screen bg-[var(--background)] py-10 px-4">
      <div className="mx-auto max-w-5xl">
        {/* Header */}
        <div className="flex items-center justify-between mb-8">
          <Button variant="ghost" onClick={() => router.push("/plan")}>
            <ArrowLeft className="h-4 w-4" /> Edit Plan
          </Button>
          <div className="text-center">
            <h1 className="font-heading text-2xl font-bold">Your {goalLabel} Plan</h1>
            <p className="text-sm text-[var(--muted-foreground)]">
              BMR: {plan.bmr} kcal · TDEE: {plan.tdee} kcal
            </p>
          </div>
          <Button
            variant="outline"
            size="sm"
            onClick={() => { setSeed((s) => s + 100); setSaved(false); setSaveError(""); }}
            disabled={!!planId || mealsLoading}
            title={planId ? "Saved plans are fixed — start a new plan to regenerate" : "Generate a different set of meals"}
          >
            <RefreshCw className="h-4 w-4" /> Regenerate
          </Button>
        </div>

        {/* Macro summary cards */}
        <div className="grid grid-cols-2 lg:grid-cols-4 gap-4 mb-6">
          {MACRO_CARDS.map((m, i) => (
            <motion.div
              key={m.key}
              initial={{ opacity: 0, y: 20 }}
              animate={{ opacity: 1, y: 0 }}
              transition={{ delay: i * 0.08 }}
            >
              <Card className="text-center p-4">
                <m.icon className={`h-6 w-6 mx-auto mb-2 ${m.color}`} />
                <div className="font-heading text-2xl font-bold">
                  {plan[m.key]}
                  <span className="text-sm font-normal text-[var(--muted-foreground)] ml-1">{m.unit}</span>
                </div>
                <div className="text-xs text-[var(--muted-foreground)] mt-1">{m.label}</div>
              </Card>
            </motion.div>
          ))}
        </div>

        {/* BMI card */}
        {bmiInfo && (
          <motion.div initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.4 }} className="mb-8">
            <Card className="p-4">
              <div className="flex items-center justify-between mb-2">
                <span className="text-xs font-medium text-[var(--muted-foreground)] uppercase tracking-wide">Body Mass Index (BMI)</span>
                <span className={`text-xs font-semibold px-2 py-0.5 rounded-full bg-[var(--secondary)] ${bmiInfo.color}`}>{bmiInfo.category}</span>
              </div>
              <div className="flex items-end gap-2 mb-3">
                <span className={`font-heading text-3xl font-bold ${bmiInfo.color}`}>{bmi}</span>
                <span className="text-xs text-[var(--muted-foreground)] mb-1">kg/m²</span>
              </div>
              <div className="relative h-2 rounded-full overflow-hidden bg-gradient-to-r from-blue-400 via-green-400 via-amber-400 to-red-500">
                <div
                  className="absolute top-1/2 -translate-y-1/2 w-3 h-3 rounded-full bg-white border-2 border-[var(--foreground)] shadow"
                  style={{ left: `calc(${bmiPct}% - 6px)` }}
                />
              </div>
              <div className="flex justify-between text-[10px] text-[var(--muted-foreground)] mt-1">
                <span>Underweight &lt;18.5</span><span>Normal 18.5–25</span><span>Overweight 25–30</span><span>Obese &gt;30</span>
              </div>
            </Card>
          </motion.div>
        )}

        {/* Chart + breakdown */}
        <div className="grid lg:grid-cols-2 gap-6 mb-10">
          <Card>
            <CardHeader><CardTitle>Macro Breakdown</CardTitle></CardHeader>
            <CardContent>
              <MacroDonutChart proteinG={plan.proteinG} carbsG={plan.carbsG} fatG={plan.fatG} />
            </CardContent>
          </Card>

          <Card>
            <CardHeader><CardTitle>How We Got Here</CardTitle></CardHeader>
            <CardContent className="flex flex-col gap-4 pt-2">
              {[
                { label: "Basal Metabolic Rate (BMR)", value: `${plan.bmr} kcal`, desc: "Calories your body burns at rest" },
                { label: "Total Daily Energy (TDEE)", value: `${plan.tdee} kcal`, desc: `BMR × ${stats.activityLevel.replace("_", " ")} multiplier` },
                {
                  label: "Goal Adjustment",
                  value: stats.goal === "maintain" ? "None" : stats.goal === "lose" ? `−${plan.tdee - plan.calories} kcal` : `+${plan.calories - plan.tdee} kcal`,
                  desc: `For ${stats.goal === "maintain" ? "maintenance" : `${stats.targetRateKg}kg/week`}`,
                },
                { label: "Your Daily Target", value: `${plan.calories} kcal`, desc: "What you should eat each day", highlight: true },
              ].map((row) => (
                <div key={row.label} className={`flex items-start justify-between gap-4 rounded-lg p-3 ${row.highlight ? "bg-[var(--accent)]" : "bg-[var(--secondary)]/50"}`}>
                  <div>
                    <div className={`text-sm font-medium ${row.highlight ? "text-[var(--primary)]" : ""}`}>{row.label}</div>
                    <div className="text-xs text-[var(--muted-foreground)]">{row.desc}</div>
                  </div>
                  <div className={`font-heading font-bold text-sm whitespace-nowrap ${row.highlight ? "text-[var(--primary)]" : ""}`}>{row.value}</div>
                </div>
              ))}
            </CardContent>
          </Card>
        </div>

        {/* Meal plan */}
        <div className="mb-8">
          <div className="flex items-center justify-between mb-2">
            <h2 className="font-heading text-2xl font-bold">Today&apos;s Meal Plan</h2>
            <span className="text-sm text-[var(--muted-foreground)] capitalize">{dietType.replace("_", "-")} diet</span>
          </div>
          {!mealsLoading && source && (
            <p className="text-xs text-[var(--muted-foreground)] mb-5">
              {SOURCE_LABELS[source]}{allergies.length > 0 ? ` · Excludes: ${allergies.join(", ")}` : ""}
            </p>
          )}

          {mealsLoading ? (
            <MealLoadingSkeleton fromSaved={!!planId} />
          ) : meals && hasMealPlanContent(meals) ? (
            <AnimatePresence>
            <div className="grid sm:grid-cols-2 gap-5">
              {MEAL_ORDER.map((time) => {
                const items: FoodItem[] = meals[time] ?? [];
                if (items.length === 0) return null;
                return (
                  <div key={time}>
                    <h3 className="font-heading font-semibold text-sm text-[var(--muted-foreground)] uppercase tracking-wide mb-3">
                      {MEAL_LABELS[time]}
                    </h3>
                    <div className="flex flex-col gap-3">
                      {items.map((item) => (
                        <motion.div
                          key={item.id}
                          initial={{ opacity: 0, x: -10 }}
                          animate={{ opacity: 1, x: 0 }}
                          transition={{ duration: 0.3 }}
                        >
                          <Card className="overflow-hidden hover:shadow-md transition-shadow">
                            <div className="flex">
                              <div className="relative w-24 h-24 flex-shrink-0">
                                <Image src={item.image} alt={item.name} fill className="object-cover" sizes="96px" />
                              </div>
                              <CardContent className="p-3 flex flex-col justify-between flex-1">
                                <div>
                                  <div className="flex items-start justify-between gap-1">
                                    <h4 className="font-semibold text-sm leading-tight">{item.name}</h4>
                                    {item.aiGenerated && (
                                      <span className="text-[10px] bg-[var(--primary)]/10 text-[var(--primary)] rounded-full px-1.5 py-0.5 whitespace-nowrap flex-shrink-0">✦ AI</span>
                                    )}
                                  </div>
                                  {item.description && (
                                    <p className="text-xs text-[var(--muted-foreground)] mt-0.5 leading-snug line-clamp-2">{item.description}</p>
                                  )}
                                  <p className="text-xs text-[var(--muted-foreground)] mt-0.5">{item.servingSize}</p>
                                </div>
                                <div className="flex gap-3 text-xs mt-2">
                                  <span className="text-orange-500 font-medium">{item.calories} kcal</span>
                                  <span className="text-green-600">P: {item.proteinG}g</span>
                                  <span className="text-amber-500">C: {item.carbsG}g</span>
                                  <span className="text-orange-400">F: {item.fatG}g</span>
                                </div>
                              </CardContent>
                            </div>
                          </Card>
                        </motion.div>
                      ))}
                    </div>
                  </div>
                );
              })}
            </div>
            </AnimatePresence>
          ) : (
            <div role="alert" className="rounded-xl border border-[var(--border)] bg-[var(--card)] p-6 text-center">
              <p className="text-sm text-[var(--muted-foreground)]">{loadError || "Could not load meal plan."}</p>
              {!planId && (
                <Button variant="outline" size="sm" className="mt-4" onClick={() => setSeed((s) => s + 1)}>
                  <RefreshCw className="h-4 w-4" /> Try again
                </Button>
              )}
              {planId && loadError.startsWith("Please sign in") && (
                <Button size="sm" className="mt-4" onClick={() => router.push(`/auth/signin?callbackUrl=${encodeURIComponent(window.location.pathname + window.location.search)}`)}>
                  Sign in
                </Button>
              )}
            </div>
          )}
        </div>

        {/* Save CTA */}
        <Card className="bg-[var(--accent)] border-[var(--primary)]/30 p-6 sm:p-8">
          <div className="flex flex-col sm:flex-row items-center justify-between gap-4">
            <div>
              <h3 className="font-heading text-xl font-bold mb-1">
                {saved ? "Plan saved! 🎉" : session ? "Save this plan" : "Save your plan"}
              </h3>
              <p className="text-sm text-[var(--muted-foreground)]">
                {saved
                  ? fromSaved
                    ? "This plan is already in your dashboard."
                    : "View it anytime in your dashboard."
                  : session
                  ? "Add this plan to your dashboard to track progress."
                  : "Create a free account to save this plan and track progress."}
              </p>
              {saveError && <p role="alert" className="text-sm text-[var(--destructive)] mt-1">{saveError}</p>}
            </div>
            <div className="flex gap-3 flex-shrink-0">
              {saved ? (
                <Button onClick={() => router.push("/dashboard")}>
                  <BookmarkCheck className="h-4 w-4" /> View Dashboard
                </Button>
              ) : (
                <Button onClick={handleSave} disabled={saving || status === "loading" || mealsLoading || !canSave}>
                  {saving
                    ? <><Loader2 className="h-4 w-4 animate-spin" /> Saving…</>
                    : <><Bookmark className="h-4 w-4" /> {session ? "Save Plan" : "Sign Up & Save"}</>}
                </Button>
              )}
              <Button variant="outline" onClick={() => router.push("/plan")}>Start Over</Button>
            </div>
          </div>
        </Card>
      </div>
    </div>
  );
}
